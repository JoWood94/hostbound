const GAP = 0.26;                       // space between glyphs, in em

const glyphOf = (ch) => G[ch] || G[ch.toUpperCase()] || G[' '];   // other lowercase: capitals

export function wordWidth(str, size) {
  let w = 0;
  for (const ch of str) w += (glyphOf(ch)[0] + GAP) * size;
  return w - GAP * size;
}

// Draws `str` with its top-left at (x, y), glyph height `size`. Lowercase is
// drawn as capitals. progress (0..1) traces each glyph in, one after another.
export function drawWord(str, x, y, size, color, { weight = 0.13, align = 'left', progress = 1 } = {}) {
  if (align === 'center') x -= wordWidth(str, size) / 2;
  else if (align === 'right') x -= wordWidth(str, size);
  ctx.save();
  ctx.strokeStyle = color; ctx.fillStyle = color;
  ctx.lineWidth = Math.max(1.1, size * weight); ctx.lineCap = 'round'; ctx.lineJoin = 'round';
  const chars = [...str];
  // Strokes of the whole word go into one path, stroked once.
  ctx.beginPath();
  const dots = [];
  chars.forEach((ch, ci) => {
    const [w, strokes] = glyphOf(ch);
    const local = progress >= 1 ? 1 : Math.max(0, Math.min(1, progress * (chars.length + 2) / 3 - ci / 3));
    const n = Math.ceil(strokes.length * local);
    for (let i = 0; i < n; i++) {
      const s = strokes[i];
      if (s[0] === 'L') { ctx.moveTo(x + s[1] * size, y + s[2] * size); ctx.lineTo(x + s[3] * size, y + s[4] * size); }
      else if (s[0] === 'A') {
        const cx = x + s[1] * size, cy = y + s[2] * size, r = s[3] * size;
        ctx.moveTo(cx + Math.cos(s[4]) * r, cy + Math.sin(s[4]) * r);
        ctx.arc(cx, cy, r, s[4], s[5], !!s[6]);
      } else dots.push(s, x);
    }
    x += (w + GAP) * size;
  });
  ctx.stroke();
  for (let i = 0; i < dots.length; i += 2) {
    const s = dots[i], ox = dots[i + 1];
    ctx.beginPath();
    if (s[0] === 'D') ctx.arc(ox + s[1] * size, y + s[2] * size, Math.max(ctx.lineWidth * 0.62, s[3] * size), 0, P * 2);
    else { ctx.moveTo(ox + s[1] * size, y + s[2] * size); ctx.lineTo(ox + s[3] * size, y + s[4] * size); ctx.lineTo(ox + s[5] * size, y + s[6] * size); ctx.closePath(); ctx.stroke(); }
    ctx.fill();
  }
  ctx.restore();
}
